class OwnerCopilotEngine:
    @staticmethod
    def navigate_ui(query: str) -> List[UINavResult]:
        q_lower = query.lower()
        tokens = set(re.findall(r"\w+", q_lower))
        matches: List[Tuple[int, Dict[str, Any]]] = []

        for item in PLATFORM_UI_CATALOG:
            score = 0
            for kw in item["keywords"]:
                if kw in q_lower:
                    score += 3
                for t in tokens:
                    if t in kw:
                        score += 1

            if score > 0:
                matches.append((score, item))

        matches.sort(key=lambda x: x[0], reverse=True)

        results = []
        for _, item in matches[:3]:
            results.append(
                UINavResult(
                    screen_name=item["screen_name"],
                    route_path=item["route_path"],
                    breadcrumbs=item["breadcrumbs"],
                    description=item["description"],
                    action_available=item["action_available"],
                    suggested_action_payload=None
                )
            )

        if not results:
            results.append(
                UINavResult(
                    screen_name="Cockpit Main Dashboard",
                    route_path="/kanban",
                    breadcrumbs=["Cockpit", "Kanban"],
                    description="Central operational view of active projects, agent pool, and task statuses.",
                    action_available=None
                )
            )

        return results

    @staticmethod
    async def explain_trace(db: AsyncSession, correlation_id: str) -> TraceExplanation:
        stmt = (
            select(AuditLog)
            .where(AuditLog.correlation_id == correlation_id)
            .order_by(AuditLog.created_at.asc())
        )
        res = await db.execute(stmt)
        logs = res.scalars().all()

        if not logs:
            return TraceExplanation(
                correlation_id=correlation_id,
                task_id=None,
                agent_id=None,
                daemon_id=None,
                total_events=0,
                has_errors=False,
                root_cause_summary=f"No audit logs found for Correlation ID '{correlation_id}'.",
                timeline=[],
                suggested_remedy="Verify the Correlation ID or check if logging is enabled on the daemon."
            )

        first_log = logs[0]
        task_id = first_log.task_id
        agent_id = first_log.agent_id
        daemon_id = first_log.daemon_id

        timeline = []
        has_errors = False
        error_events = []

        for log in logs:
            if log.task_id and not task_id:
                task_id = log.task_id
            if log.agent_id and not agent_id:
                agent_id = log.agent_id
            if log.daemon_id and not daemon_id:
                daemon_id = log.daemon_id

            if log.level in ("ERROR", "WARN") or "REAPED" in log.event_type or "TIMEOUT" in log.event_type:
                has_errors = True
                error_events.append(log)

            timeline.append({
                "timestamp": log.created_at.isoformat(),
                "event_type": log.event_type,
                "level": log.level,
                "message": log.message,
                "payload": log.payload
            })

        root_cause = "Execution proceeded normally without logged failures."
        remedy = "No remediation needed."

        if any(e.event_type == "DLQ_REAPED" for e in error_events):
            root_cause = (
                "Daemon Heartbeat Failure: The local execution daemon stopped sending 15-second heartbeat pings. "
                "The 60-second database lock expired, causing the background sweeper to reap the task into the Dead-Letter Queue (DLQ)."
            )
            remedy = (
                "Check the daemon host machine for OOM kills, process crashes, or network disconnects. "
                "Restart the local daemon client with `python -m packages.daemon.folks_daemon.main` and trigger task retry via `/api/v1/owner/copilot/action/retry-dlq`."
            )
        elif any(e.event_type == "WAR_ROOM_INVITE_REJECTED" for e in error_events):
            root_cause = (
                "War Room Busy Rejection: An agent invited to consultation rejected the invitation because it was already actively "
                "executing another locked task (Strict State Machine mandate)."
            )
            remedy = (
                "Wait for the invited agent to complete its current task, or invite an alternative agent whose status is 'IDLE'."
            )
        elif error_events:
            last_err = error_events[-1]
            root_cause = f"Failure detected during {last_err.event_type}: {last_err.message}"
            remedy = "Inspect daemon terminal stderr output and verify tool permissions or required credentials."

        return TraceExplanation(
            correlation_id=correlation_id,
            task_id=task_id,
            agent_id=agent_id,
            daemon_id=daemon_id,
            total_events=len(logs),
            has_errors=has_errors,
            root_cause_summary=root_cause,
            timeline=timeline,
            suggested_remedy=remedy
        )

    @staticmethod
    async def update_agent_budget(
        db: AsyncSession,
        req: UpdateAgentBudgetRequest
    ) -> CopilotActionResponse:
        stmt = select(Agent).where(Agent.id == req.agent_id)
        res = await db.execute(stmt)
        agent = res.scalar_one_or_none()
        if not agent:
            return CopilotActionResponse(
                success=False,
                action="update_agent_budget",
                message=f"Agent with ID '{req.agent_id}' does not exist."
            )

        old_budget = float(agent.monthly_budget_usd)
        agent.monthly_budget_usd = req.monthly_budget_usd
        await db.flush()

        return CopilotActionResponse(
            success=True,
            action="update_agent_budget",
            message=f"Updated budget for agent '{agent.name}' from ${old_budget:.2f} to ${req.monthly_budget_usd:.2f}/mo.",
            data={"agent_id": agent.id, "name": agent.name, "new_budget_usd": req.monthly_budget_usd}
        )

    @staticmethod
    async def assign_project_tag(
        db: AsyncSession,
        req: AssignProjectTagRequest
    ) -> CopilotActionResponse:
        stmt = select(Agent).where(Agent.id == req.agent_id)
        res = await db.execute(stmt)
        agent = res.scalar_one_or_none()
        if not agent:
            return CopilotActionResponse(
                success=False,
                action="assign_project_tag",
                message=f"Agent with ID '{req.agent_id}' does not exist."
            )

        current_tags = list(agent.project_tags or [])
        if req.project_tag not in current_tags:
            current_tags.append(req.project_tag)
            agent.project_tags = current_tags
            await db.flush()

        return CopilotActionResponse(
            success=True,
            action="assign_project_tag",
            message=f"Assigned project tag '{req.project_tag}' to agent '{agent.name}'. Total tags: {agent.project_tags}",
            data={"agent_id": agent.id, "project_tags": agent.project_tags}
        )

    @staticmethod
    async def retry_dlq_task(
        db: AsyncSession,
        req: RetryDLQTaskRequest
    ) -> CopilotActionResponse:
        stmt = select(Task).where(Task.id == req.task_id)
        res = await db.execute(stmt)
        task = res.scalar_one_or_none()
        if not task:
            return CopilotActionResponse(
                success=False,
                action="retry_dlq_task",
                message=f"Task with ID '{req.task_id}' does not exist."
            )

        if task.status != "DEAD_LETTER_QUEUE":
            return CopilotActionResponse(
                success=False,
                action="retry_dlq_task",
                message=f"Task is in status '{task.status}', not in DEAD_LETTER_QUEUE."
            )

        task.status = "QUEUED"
        task.lock_owner_id = None
        task.lock_expires_at = None
        task.assigned_agent_id = None
        prev_dlq_reason = task.dlq_reason
        task.dlq_reason = None

        audit = AuditLog(
            correlation_id=task.correlation_id or "owner-dlq-retry",
            task_id=task.id,
            event_type="DLQ_RETRY_INITIATED",
            level="INFO",
            message=f"Task {task.id} moved from DLQ back to QUEUED by Owner Copilot.",
            payload={"comment": req.comment, "previous_dlq_reason": prev_dlq_reason}
        )
        db.add(audit)
        await db.flush()

        return CopilotActionResponse(
            success=True,
            action="retry_dlq_task",
            message=f"Task '{task.title}' successfully requeued from DLQ for processing.",
            data={"task_id": task.id, "status": task.status, "project_tag": task.project_tag}
        )
